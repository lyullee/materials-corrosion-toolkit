"""Verify reviewed pulse-echo series conversion against an independent distance identity."""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from matintegrity.contracts import Evidence
from matintegrity.ultrasound_data import (
    PulseEchoThicknessCalibration,
    pulse_echo_thickness_observations,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "validation/pulse_echo_thickness_math.json"


def main():
    sound_speed_m_s = 5920.0
    thickness_m = 0.0075
    time_zero_offset_s = 35e-9
    round_trip_time_s = 2 * thickness_m / sound_speed_m_s + time_zero_offset_s
    series = {
        "source_id": "authored-synthetic-pulse-echo",
        "series_id": "exact-distance-identity",
        "reported_tof_unit": "s",
        "observations": [
            {
                "source_order": 0,
                "timestamp": datetime(2026, 1, 1),
                "observational_unit_id": "synthetic-location",
                "sample_id": "synthetic-coupon",
                "piezo_id": "synthetic-longitudinal-probe",
                "tof_s": round_trip_time_s,
                "tof_compensated_s": round_trip_time_s,
            }
        ],
    }
    calibration = PulseEchoThicknessCalibration(
        calibration_id="authored-exact-distance-calibration",
        material_id="synthetic-homogeneous-solid",
        applicable_sample_ids=("synthetic-coupon",),
        applicable_probe_ids=("synthetic-longitudinal-probe",),
        wave_mode="longitudinal",
        sound_speed_m_s=sound_speed_m_s,
        sound_speed_temperature_K=293.15,
        time_zero_offset_s=time_zero_offset_s,
        tof_field="tof_s",
        calibration_basis="authored exact round-trip distance identity",
        evidence=Evidence(
            source_id="authored-pulse-echo-identity",
            origin="synthetic",
            citation="independent algebraic verification generated by this project",
        ),
        calibration_reviewed=True,
    )
    result = pulse_echo_thickness_observations(series, calibration=calibration)
    computed_m = result["observations"][0]["remaining_thickness_m"]
    absolute_error_m = abs(computed_m - thickness_m)
    if absolute_error_m > 1e-15:
        raise ValueError("pulse-echo exact-distance identity failed")
    report = {
        "schema": "matintegrity.pulse_echo_thickness_math.v1",
        "case": "authored homogeneous normal-incidence round-trip path",
        "expected_thickness_m": thickness_m,
        "computed_thickness_m": computed_m,
        "absolute_error_m": absolute_error_m,
        "calibration_digest": result["calibration_digest"],
        "identity_gate_checked_by_unit_tests": True,
        "unreviewed_calibration_gate_checked_by_unit_tests": True,
        "compensated_tof_basis_gate_checked_by_unit_tests": True,
        "qualification": (
            "Software and algebraic verification only; no material, probe, field calibration or "
            "measurement uncertainty is experimentally validated by this synthetic case."
        ),
    }
    OUTPUT.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
