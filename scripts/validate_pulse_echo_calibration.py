"""Independently verify the reference-block sound-speed fit and holdout separation."""

import json
import math
from pathlib import Path

from matintegrity.contracts import Evidence
from matintegrity.models.inspection import PulseEchoSoundSpeedFit, pulse_echo_sound_speed_fit

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "validation/pulse_echo_calibration_math.json"


def main():
    expected_speed = 5920.0
    offset = 30e-9
    calibration_thicknesses = [0.004, 0.006, 0.008]
    holdout_thickness = 0.010

    def observation(index, thickness, partition, group):
        return {
            "observation_id": f"synthetic-{index}",
            "physical_location_id": f"location-{index}",
            "source_group_id": group,
            "partition": partition,
            "reference_thickness_m": thickness,
            "round_trip_time_s": 2 * thickness / expected_speed + offset,
        }

    values = {
        "calibration_id": "authored-exact-reference-fit",
        "material_id": "synthetic-homogeneous-solid",
        "probe_id": "synthetic-longitudinal-probe",
        "temperature_K": 293.15,
        "time_zero_offset_s": offset,
        "incidence_angle_rad": 0.0,
        "reference_dimension_method": "authored exact synthetic dimensions",
        "observations": [
            *[
                observation(i, thickness, "calibration", f"calibration-{i}")
                for i, thickness in enumerate(calibration_thicknesses)
            ],
            observation(3, holdout_thickness, "holdout", "holdout-3"),
        ],
        "timing_and_path_reviewed": True,
        "reference_dimensions_reviewed": True,
        "holdout_partition_predeclared": True,
        "evidence": (
            Evidence(
                source_id="authored-pulse-echo-fit-identity",
                origin="synthetic",
                citation="independent algebraic verification generated by this project",
            ),
        ),
    }
    result = pulse_echo_sound_speed_fit(PulseEchoSoundSpeedFit(**values)).values
    x = [0.5 * (row["round_trip_time_s"] - offset) for row in values["observations"][:3]]
    y = calibration_thicknesses
    independent_speed = sum(a * b for a, b in zip(x, y, strict=True)) / sum(a * a for a in x)
    absolute_error = abs(result["sound_speed_m_s"] - independent_speed)
    if absolute_error > 1e-10 or result["holdout_rmse_m"] > 1e-15:
        raise ValueError("pulse-echo reference-block identity failed")
    altered = dict(values)
    altered_rows = [dict(row) for row in values["observations"]]
    altered_rows[-1]["reference_thickness_m"] += 0.001
    altered["observations"] = altered_rows
    altered_result = pulse_echo_sound_speed_fit(PulseEchoSoundSpeedFit(**altered)).values
    holdout_excluded = math.isclose(
        altered_result["sound_speed_m_s"], result["sound_speed_m_s"], rel_tol=0, abs_tol=0
    )
    if not holdout_excluded:
        raise ValueError("holdout observation changed the calibration fit")
    uncertainty_values = dict(values)
    uncertainty_values["fit_method"] = "iterative_effective_variance"
    uncertainty_values["observations"] = [
        {
            **row,
            "reference_thickness_standard_uncertainty_m": 2e-6,
            "round_trip_time_standard_uncertainty_s": 1e-9,
        }
        for row in values["observations"]
    ]
    uncertainty_result = pulse_echo_sound_speed_fit(PulseEchoSoundSpeedFit(**uncertainty_values)).values
    sigma_x = 0.5e-9
    point_variance = (2e-6) ** 2 + expected_speed**2 * sigma_x**2
    expected_standard_error = math.sqrt(1.0 / sum(path**2 / point_variance for path in x))
    uncertainty_error = abs(uncertainty_result["sound_speed_standard_error_m_s"] - expected_standard_error)
    if uncertainty_error > 1e-12:
        raise ValueError("pulse-echo effective-variance uncertainty identity failed")
    report = {
        "schema": "matintegrity.pulse_echo_calibration_math.v1",
        "expected_sound_speed_m_s": expected_speed,
        "computed_sound_speed_m_s": result["sound_speed_m_s"],
        "independent_closed_form_sound_speed_m_s": independent_speed,
        "absolute_error_m_s": absolute_error,
        "holdout_rmse_m": result["holdout_rmse_m"],
        "holdout_excluded_from_fit": holdout_excluded,
        "effective_variance_standard_error_m_s": uncertainty_result["sound_speed_standard_error_m_s"],
        "independent_effective_variance_standard_error_m_s": expected_standard_error,
        "effective_variance_standard_error_absolute_difference_m_s": uncertainty_error,
        "qualification": (
            "Synthetic algebra and partition verification only; no reference block, probe, "
            "material, dimensional metrology or field transfer is experimentally qualified."
        ),
    }
    OUTPUT.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
