"""Inspect the pinned FABEST workbook without executing macros or fitting a service curve."""

from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

import openpyxl

from matintegrity.fatigue_data import read_fabest

ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "data/raw/fabest/FAB_v20260730.xlsm"


def inspect_fabest_data(path: Path = WORKBOOK) -> dict:
    payload = path.read_bytes()
    workbook = openpyxl.load_workbook(path, read_only=True, data_only=True, keep_vba=False)
    try:
        worksheets = len(workbook.sheetnames)
    finally:
        workbook.close()

    loaded = read_fabest(path)
    observations = loaded["observations"]
    groups = loaded["groups"]
    comment_tag_rows = Counter(tag for tags in observations.comment_review_tags for tag in tags)
    result = {
        "source_id": "fabest",
        "source_sha256": hashlib.sha256(payload).hexdigest(),
        "source_bytes": len(payload),
        "worksheets": worksheets,
        "macro_execution": loaded["macro_execution"],
        "high_cycle_observation_groups": len(groups),
        "high_cycle_observations": len(observations),
        "valid_endpoint_rows": int(observations.row_valid.sum()),
        "endpoint_contract_status_rows": (
            observations.endpoint_contract_status.value_counts().sort_index().to_dict()
        ),
        "calibration_role_rows": (observations.calibration_role.value_counts().sort_index().to_dict()),
        "provider_interrupted_rows": int(observations.provider_interrupted.sum()),
        "provider_interrupted_with_review_comment_rows": int(
            (observations.provider_interrupted & observations.endpoint_needs_review).sum()
        ),
        "groups_with_reported_end_criterion": sum(
            group["end_criterion_status"] == "reported" for group in groups
        ),
        "groups_without_reported_end_criterion": sum(
            group["end_criterion_status"] == "absent" for group in groups
        ),
        "source_quality_groups": dict(
            sorted(Counter(group["acquisition_description"] for group in groups).items())
        ),
        "letter_suffix_semantics_unresolved_rows": int(
            observations.specimen_label_suffix_status.eq("letter_suffix_semantics_unresolved").sum()
        ),
        "rows_with_endpoint_comments": int(observations.endpoint_needs_review.sum()),
        "comment_review_tag_rows": dict(sorted(comment_tag_rows.items())),
        "reported_comment_temperature_rows": int(
            observations.reported_comment_temperature_degC.notna().sum()
        ),
        "break_cycle_with_no_crack_comment_rows": int(
            (
                observations.cycles_to_reported_break.notna()
                & observations.comment_review_tags.map(lambda tags: "reported_no_crack" in tags)
            ).sum()
        ),
        "physical_specimen_independence_reviewed_rows": int(
            observations.physical_specimen_independence_reviewed.sum()
        ),
        "static_reference_points_excluded": len(loaded["static_reference_points"]),
        "regression_points_excluded": sum(group["fitted_curve_rows_excluded"] for group in groups),
        "strain_life_observations": len(loaded["strain_life_observations"]),
        "qualification": (
            "Provider finish/interruption and reported-break cycles are separate fields. The curve "
            "sheets do not report an END criterion, letter suffixes have unresolved semantics, and "
            "free-text tags are review aids only. Interruption is not automatically a runout, comment "
            "temperatures are not qualified specimen temperatures, and no service S-N curve or physical-"
            "specimen independence is claimed."
        ),
    }
    expected = {
        "source_sha256": "57b2f359ef5c822be34068a3dfa0b78b5b8291d00a0f0f49a056f4ef8b574bf8",
        "source_bytes": 9_156_667,
        "worksheets": 73,
        "macro_execution": False,
        "high_cycle_observation_groups": 60,
        "high_cycle_observations": 663,
        "valid_endpoint_rows": 662,
        "endpoint_contract_status_rows": {
            "reported_break_cycle": 567,
            "reported_interruption": 95,
            "unresolved": 1,
        },
        "calibration_role_rows": {
            "candidate_censored_observation": 80,
            "candidate_failure_observation": 451,
            "needs_specimen_protocol_review": 131,
            "unresolved_endpoint": 1,
        },
        "provider_interrupted_rows": 95,
        "provider_interrupted_with_review_comment_rows": 15,
        "groups_with_reported_end_criterion": 0,
        "groups_without_reported_end_criterion": 60,
        "source_quality_groups": {
            "graph generated by computer": 5,
            "raw data in numbers": 55,
        },
        "letter_suffix_semantics_unresolved_rows": 54,
        "rows_with_endpoint_comments": 89,
        "comment_review_tag_rows": {
            "reported_comment_temperature": 8,
            "reported_crack_or_break": 52,
            "reported_excluded": 2,
            "reported_grip_fretting": 1,
            "reported_mistake": 1,
            "reported_no_crack": 18,
            "reported_possible_buckling": 3,
            "reported_thread_damage": 13,
        },
        "reported_comment_temperature_rows": 8,
        "break_cycle_with_no_crack_comment_rows": 18,
        "physical_specimen_independence_reviewed_rows": 0,
        "static_reference_points_excluded": 60,
        "regression_points_excluded": 2_885,
        "strain_life_observations": 8,
    }
    for key, value in expected.items():
        if result[key] != value:
            raise ValueError(f"pinned FABEST workbook changed: {key}")
    return result


if __name__ == "__main__":
    print(json.dumps(inspect_fabest_data(), ensure_ascii=False, indent=2))
