@dataclass(frozen=True)
class ModelSpec:
    model_id: str
    input_type: type[Contract]
    evaluator: Callable[..., Calculation]
    units: dict[str, str]
    assumptions: tuple[str, ...]
    source_ids: tuple[str, ...]
    version: str = "1.0.0"
    qualification: str = "engineering_screening"
    context_validator: Callable[[Contract, RunContext], None] | None = None
    probability_semantics: dict[str, ProbabilityMeaning] = field(default_factory=dict)
    runtime_dependency_names: tuple[str, ...] = ()


class ModelRegistry:
    def __init__(self):
        self._models: dict[str, ModelSpec] = {}

    def register(self, spec: ModelSpec, *, replace: bool = False) -> None:
        if spec.model_id in self._models and not replace:
            raise ValueError(f"model already registered: {spec.model_id}")
        if not spec.model_id or not spec.assumptions or not spec.source_ids:
            raise ValueError("model identity, assumptions and source identifiers are required")
        if any(spec.units.get(key) != "1" for key in spec.probability_semantics):
            raise ValueError("declared probability outputs must have dimensionless units")
        if len(spec.runtime_dependency_names) != len(set(spec.runtime_dependency_names)) or any(
            not isinstance(name, str) or not name.isidentifier() for name in spec.runtime_dependency_names
        ):
            raise ValueError("runtime dependency names must be unique Python identifiers")
        self._models[spec.model_id] = spec

    def list_models(self) -> tuple[str, ...]:
        return tuple(sorted(self._models))

    def describe(self, model_id: str) -> dict:
        spec = self._models[model_id]
        return dict(
            model_id=model_id,
            model_version=spec.version,
            input_schema=spec.input_type.model_json_schema(),
            output_units=spec.units,
            assumptions=spec.assumptions,
            source_ids=spec.source_ids,
            probability_semantics=dict(spec.probability_semantics),
            runtime_dependencies=spec.runtime_dependency_names,
        )

    def input_type(self, model_id: str) -> type[Contract]:
        """Return the registered input contract type for safe adapters without dynamic imports."""
        return self._models[model_id].input_type

    def run(
        self,
        model_id: str,
        inputs: dict | Contract,
        context: RunContext,
        *,
        runtime_dependencies: Mapping[str, Any] | None = None,
    ) -> AssessmentResult:
        if not isinstance(context, RunContext):
            raise TypeError("context must be an explicit RunContext")
        spec = self._models[model_id]
        validated = spec.input_type.model_validate(inputs)
        if spec.context_validator is not None:
            spec.context_validator(validated, context)
        supplied_dependencies = dict(runtime_dependencies or {})
        expected_dependencies = set(spec.runtime_dependency_names)
        if set(supplied_dependencies) != expected_dependencies:
            missing = sorted(expected_dependencies - set(supplied_dependencies))
            unexpected = sorted(set(supplied_dependencies) - expected_dependencies)
            raise ValueError(
                f"runtime dependencies must match the model declaration; missing={missing}, unexpected={unexpected}"
            )
        calculation = (
            spec.evaluator(validated, **supplied_dependencies)
            if expected_dependencies
            else spec.evaluator(validated)
        )
        if not isinstance(calculation, Calculation):
            raise TypeError("model must return a Calculation contract")
        payload = dict(
            model_id=model_id,
            model_version=spec.version,
            inputs=validated.model_dump(mode="json"),
            context=context.model_dump(mode="json"),
        )
        return AssessmentResult(
            model_id=model_id,
            model_version=spec.version,
            status=calculation.status,
            inputs=validated.model_dump(mode="json"),
            values=deepcopy(calculation.values),
            units=dict(spec.units),
            assumptions=spec.assumptions,
            notes=calculation.notes,
            context=context.model_copy(deep=True),
            input_digest=canonical_digest(payload),
            source_ids=spec.source_ids,
            qualification=spec.qualification,
            runtime=_runtime_versions(),
            probability_semantics=dict(spec.probability_semantics),
        )

    def run_json(
        self,
        model_id: str,
        inputs_json: str,
        context: RunContext,
        *,
        runtime_dependencies: Mapping[str, Any] | None = None,
    ) -> AssessmentResult:
        """Validate JSON-native inputs and inject only the model-declared runtime dependencies."""
        validated = self._models[model_id].input_type.model_validate_json(inputs_json)
        return self.run(model_id, validated, context, runtime_dependencies=runtime_dependencies)


def _runtime_versions() -> dict[str, str]:
    runtime = {"matintegrity": __version__, "python": platform.python_version()}
    for name in ("numpy", "pydantic", "pint", "scipy", "rainflow"):
        try:
            runtime[name] = version(name)
        except PackageNotFoundError:
            continue
    return runtime


